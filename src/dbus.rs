use std::hash::{Hash, Hasher};

use qtbridge::QModelItem;
use zbus::{OwnedObjectPath, proxy};

#[allow(dead_code)]
#[derive(Debug, Default, Clone, PartialEq, QModelItem)]
pub struct Unit {
    pub name: String,
    pub description: String,
    pub load_state: String,
    pub active_state: String,
    pub sub_state: String,
    pub followed_unit: String,
    pub unit_object_path: String,
    pub job_id: u32,
    pub job_type: String,
    pub job_object_path: String,
}

#[proxy(
    interface = "org.freedesktop.systemd1.Manager",
    default_service = "org.freedesktop.systemd1",
    default_path = "/org/freedesktop/systemd1"
)]
pub trait Manager {
    async fn list_units(&self) -> zbus::Result<Vec<(
        String,          // Name
        String,          // Description
        String,          // Load state
        String,          // Active state
        String,          // Sub state
        String,          // Followed unit
        OwnedObjectPath, // Unit object path
        u32,             // Job ID
        String,          // Job type
        OwnedObjectPath, // Job object path
    )>>;

    #[zbus(allow_interactive_auth)]
    async fn start_unit(&self, name: String, mode: String) -> zbus::Result<OwnedObjectPath>;

    #[zbus(allow_interactive_auth)]
    async fn stop_unit(&self, name: String, mode: String) -> zbus::Result<OwnedObjectPath>;

    #[zbus(allow_interactive_auth)]
    async fn restart_unit(&self, name: String, mode: String) -> zbus::Result<OwnedObjectPath>;

    #[zbus(signal)]
    async fn job_removed(&self, id: u32, job: OwnedObjectPath, unit: String, result: String) -> zbus::Result<()>;
}

/// iced requires that objects passed to subscription tasks implement [Hash], which [ManagerProxy]
/// (generated by zbus) does not. This wrapper DOES implement Hash by hashing the destination, path,
/// and interface, so it can be passed to a subscription task with [iced::Subscription::run_with]
pub struct HashableManagerProxy(pub ManagerProxy<'static>);

impl Hash for HashableManagerProxy {
    fn hash<H: Hasher>(&self, state: &mut H) {
        let proxy = self.0.inner();
        proxy.destination().as_str().hash(state);
        proxy.path().as_str().hash(state);
        proxy.interface().as_str().hash(state);
    }
}
